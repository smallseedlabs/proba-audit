#!/usr/bin/env bash
# Writes a local .env with random passwords for docker-compose.yml (nothing in this repository has a default password).
#   scripts/generate-local-env.sh            -> creates .env (refuses to overwrite)
#   scripts/generate-local-env.sh --force    -> replaces .env (the old passwords stop working: `docker compose down -v` first)
# The values are hex (URL-safe: Redis and anchor-db passwords are placed inside URLs). Never commit the result; .env is gitignored.
set -euo pipefail

cd "$(dirname "$0")/.."
if [ -e .env ] && [ "${1:-}" != "--force" ]; then
  echo ".env already exists; pass --force to replace it" >&2
  exit 1
fi

secret() { openssl rand -hex "${1:-24}"; }

REDIS_PASSWORD="$(secret)"
POSTGRES_PASSWORD="$(secret)"

umask 077
cat > .env <<ENV
# Generated by scripts/generate-local-env.sh. Local only; never commit.
# Read by docker compose (passwords) and by the host-side npm scripts and tests (URLs, users).
CLICKHOUSE_URL=http://127.0.0.1:8123
CLICKHOUSE_USER=proba
CLICKHOUSE_PASSWORD=$(secret)
CLICKHOUSE_CONSUMER_USER=proba_consumer
CLICKHOUSE_CONSUMER_PASSWORD=$(secret)
CLICKHOUSE_API_USER=proba_api
CLICKHOUSE_API_PASSWORD=$(secret)
CLICKHOUSE_MIGRATOR_USER=proba_migrator
CLICKHOUSE_MIGRATOR_PASSWORD=$(secret)
REDIS_USER=proba
REDIS_PASSWORD=${REDIS_PASSWORD}
REDIS_URL=redis://proba:${REDIS_PASSWORD}@127.0.0.1:6379
POSTGRES_PASSWORD=${POSTGRES_PASSWORD}
OUTBOX_TEST_DATABASE_URL=postgresql://proba:${POSTGRES_PASSWORD}@127.0.0.1:5432/proba_audit_outbox_test
ANCHOR_DB_PASSWORD=$(secret)
ANCHOR_HMAC_KEY=$(secret 32)
ENV
echo "wrote .env with random passwords (ClickHouse admin user: proba)"
echo "next: docker compose up -d clickhouse redis && npm run migrate   (creates the append-only users and applies the migrations)"
